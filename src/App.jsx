function normalizeUrlLabel(url) {
  return String(url || "")
    .replace(/^https?:\/\//i, "")
    .replace(/^www\./i, "")
    .replace(/\/$/g, "");
}

function encodeJsonForUrl(value) {
  return encodeURIComponent(JSON.stringify(value));
}

